def train_model(profile_id: str, backend: str = "auto") -> dict[str, Any]:
    """Train the profile's feasibility model: 'azure', 'local' or 'auto' (Azure if connected)."""
    from backend.scoring import data as _data
    from backend.scoring.profiles import load_profiles

    if backend not in ("auto", "azure", "local"):
        raise ToolError("backend must be auto | azure | local")
    grid = _data.load()
    profiles = load_profiles(set(grid.layer_ids))
    if profile_id not in profiles:
        raise ToolError(f"unknown profile {profile_id!r}")
    profile = profiles[profile_id]
    from backend.scoring.ml import lightgbm_available

    if not lightgbm_available():
        return {"trained": False, "reason": "LightGBM can't load here (on macOS: brew install libomp)",
                "advice": "Scores still work; the feasibility multiplier stays 1.0."}
    if profile.model is None:
        raise ToolError("profile declares no model; add a `model` block with positives first")
    connected = azure_ml.status()["configured"] and azure_ml.sdk_installed()
    if backend in ("azure", "auto") and not connected:
        return {"action_required": "choose_training", "options": ["connect_azure", "use_aggregator"],
                "message": "Azure ML isn't connected. Connect it to train the model in the cloud, or use the "
                           "Mistral data aggregator to build this use case from aggregated data without ML training.",
                "status": azure_ml.status()}
    try:
        if backend == "azure" or (backend == "auto" and connected):
            result = azure_ml.submit(grid, profile)
        else:
            result = azure_ml.run_local(grid, profile)
    except ValueError as exc:  # e.g. too few positives in the region
        return {"trained": False, "reason": str(exc),
                "advice": "Keep the profile normative-only (remove `model`) or choose positives that exist here."}
    _scoring().reload()
    return {"trained": True, **result}


def preview_scores(profile_id: str, top_n: int = 5) -> dict[str, Any]:
    s = _scoring()
    cells = [c for c in s.score(profile_id) if not c["masked"]]
    top = sorted(cells, key=lambda c: -c["score"])[: max(1, min(top_n, 20))]
    out = []
    for c in top:
        p = s.score_point(profile_id, *_centre(c["h3"]))
        drivers = sorted(p["breakdown"].items(), key=lambda kv: -kv[1])[:3]
        out.append({"h3": c["h3"], "score": c["score"], "lat": p["lat"], "lon": p["lon"],
                    "area": _area(p["lat"], p["lon"]) if len(out) < 3 else None,
                    "top_drivers": [k for k, _ in drivers]})
    all_cells = s.score(profile_id)
    return {"profile": profile_id, "top": out, "cells": len(all_cells),
            "masked": sum(c["masked"] for c in all_cells)}


def _area(lat: float, lon: float) -> str | None:
    from backend.layers._geocode import area_name

    return area_name(lat, lon)


def _centre(cell: str) -> tuple[float, float]:
    import h3

    return h3.cell_to_latlng(cell)


def find_address(query: str | None = None, lat: float | None = None, lon: float | None = None) -> dict[str, Any]:
    """Look up an address: by text (forward geocode) or at coordinates (reverse geocode)."""
    from backend.layers import _geocode

    if query:
        hit = _geocode.lookup(query)
        if not hit:
            return {"found": False, "message": f"No address found for “{query}”."}
        return {"found": True, **hit}
    if lat is not None and lon is not None:
        addr = _geocode.address_at(float(lat), float(lon))
        return {"found": bool(addr), "address": addr, "lat": lat, "lon": lon}
    raise ToolError("give either query (an address or place) or lat and lon")


def ui_command(commands: list[dict[str, Any]]) -> dict[str, Any]:
    """An ordered queue: the UI runs each command after the previous one finishes."""
    if not commands:
        raise ToolError("send at least one command")
    bad = [c for c in commands if c.get("command") not in UI_COMMANDS]
    if bad:
        raise ToolError(f"unknown UI commands {bad}; allowed: {sorted(UI_COMMANDS)}")
    queue = [{**c, "seq": i} for i, c in enumerate(commands)]
    return {"ui": queue, "queued": len(queue)}


def request_user_action(action: str, message: str) -> dict[str, Any]:
    allowed = ("connect_azure", "choose_training", "connect_mistral", "confirm", "provide_api_key")
    if action not in allowed:
        raise ToolError(f"action must be one of {allowed}")
    out: dict[str, Any] = {"action_required": action, "message": message}
    if action == "choose_training":
        out["options"] = ["connect_azure", "use_aggregator"]
    return out


